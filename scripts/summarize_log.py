#!/usr/bin/env python3
"""Render ai-interaction-log.jsonl as a readable summary (ai-interaction-log.md)."""
import json, subprocess
from collections import Counter
from pathlib import Path

HOOK_TOOL = "git post-commit hook"


def cell(value, limit=150):
    text = " ".join(str(value or "").split()).replace("|", "/")
    return text if len(text) <= limit else text[: limit - 3] + "..."


def read_jsonl(path):
    if not path.exists():
        return []
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def main():
    root = Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())
    entries = sorted(read_jsonl(root / "ai-interaction-log.jsonl"), key=lambda e: e["timestamp"])
    ai = [e for e in entries if e.get("ai_tool") != HOOK_TOOL]
    commits = [e for e in entries if e.get("ai_tool") == HOOK_TOOL]

    tools = Counter(f'{e.get("ai_tool")} / {e.get("model")}' for e in ai)
    agents = Counter(f'{e.get("agent_name")} ({e.get("agent_type")}, {e.get("mode")})' for e in ai)
    outcomes = Counter(e.get("status") or "n/a" for e in ai)
    skills = sorted({s.get("name") for e in ai for s in e.get("skills_used", []) if s.get("name")})
    subagents = sorted({s.get("name") for e in ai for s in e.get("subagents_used", []) if s.get("name")})
    tool_use = Counter(t for e in ai for t in e.get("tools_used", []))
    mcp = sorted({m.get("server") for e in entries for m in e.get("mcp_tools_used", []) if m.get("server")})
    human = [e for e in ai if e.get("human_decision")]
    evidence = [e for e in ai if e.get("action_verification")]
    rebuilt = [e for e in ai if "Reconstructed" in (e.get("limitation") or "")]

    ev = read_jsonl(root / "ai-hook-events.jsonl")
    sessions = {e.get("session_id") for e in ev if e.get("session_id")}
    calls = Counter(e.get("tool_name") for e in ev if e.get("hook_event_name") == "PostToolUse")

    out = ["# AI Interaction Log (readable summary)", "",
           "Generated from `ai-interaction-log.jsonl` by `scripts/summarize_log.py`. The JSONL file is the source of truth; do not edit this file by hand.", "",
           "## At a glance", "",
           f"- AI interactions: {len(ai)}; commits recorded automatically by the git hook: {len(commits)}",
           "- Tools and models: " + "; ".join(f"{k} ({v})" for k, v in tools.most_common()),
           "- Agents: " + "; ".join(f"{k} ({v})" for k, v in agents.most_common()),
           "- Outcomes: " + ", ".join(f"{k} ({v})" for k, v in outcomes.most_common()),
           f"- Human oversight recorded: {len(human)} of {len(ai)} interactions; verification evidence recorded: {len(evidence)} of {len(ai)}",
           "- Skills used: " + (", ".join(skills) or "none recorded"),
           "- Sub-agents used: " + (", ".join(subagents) or "none recorded"),
           "- Tools used: " + (", ".join(f"{k} ({v})" for k, v in tool_use.most_common(8)) or "none recorded"),
           "- MCP servers used: " + (", ".join(mcp) or "none"),
           f"- Entries reconstructed afterwards (see their limitation field): {len(rebuilt)}; later entries were written live",
           ("- Captured automatically by Copilot hooks: " + f"{len(sessions)} sessions, {sum(calls.values())} tool calls "
            + "(" + ", ".join(f"{k} {v}" for k, v in calls.most_common(5)) + ")") if ev
           else "- Captured automatically by Copilot hooks: no events recorded", ""]

    out += ["## Human oversight (what I decided, corrected and verified)", ""]
    for e in human:
        out.append(f'- {e["timestamp"][:10]} **{e.get("stage")}** [{e.get("status")}]: {cell(e["human_decision"], 320)}')

    out += ["", "## Timeline of AI interactions", "",
            "| # | Time (UTC) | Tool / model | Agent (type, mode) | Request | Outcome | Evidence |", "|---|---|---|---|---|---|---|"]
    for i, e in enumerate(ai, 1):
        out.append(f'| {i} | {e["timestamp"].replace("T", " ")[:16]} | {cell(e.get("ai_tool"), 40)} / {cell(e.get("model"), 30)} | '
                   f'{cell(e.get("agent_name"), 30)} ({e.get("agent_type")}, {e.get("mode")}) | {cell(e.get("request"))} | '
                   f'{e.get("status")} | {cell(e.get("action_verification"), 110)} |')

    out += ["", "## Commits recorded automatically by the post-commit hook", "", "| Time (UTC) | Commit | Message |", "|---|---|---|"]
    for e in commits:
        out.append(f'| {e["timestamp"].replace("T", " ")[:16]} | {cell(",".join(e.get("related_ids", [])), 12)} | {cell(e.get("suggestion"), 100)} |')

    (root / "ai-interaction-log.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
